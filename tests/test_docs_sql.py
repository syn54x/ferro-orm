"""The SQL the query and mutation guides show is the SQL Ferro sends.

A page never carries SQL a person typed. Every ```sql block on the Queries,
Aggregations, Relationships and Mutations guides opens with a marker line
naming where its SQL comes from::

    -- predicates.py:first-query (sqlite)

that is, an example script in ``docs/examples/``, one of its snippet regions
(``# --8<-- [start:first-query]`` ... ``[end:first-query]``) and the dialect.
The block holds every statement that region sends, in order: a query
terminal's statement as its ``.sql()`` renders it, and any other statement
(``save()``, ``create()``, ``bulk_create()``, ``delete()`` on an instance, a
many-to-many ``add()``) as the statement log records it. Schema statements
(``migrate``), Postgres catalog probes (``catalog``), session settings and a
``transaction()`` block's own ``BEGIN`` / ``COMMIT`` are not shown.

Each statement is laid out with one clause per line (``layout``), ends with
``;`` and is set off from the next by a blank line. Joining a statement's
lines with single spaces gives back the rendered SQL byte for byte, so the
layout adds line breaks and nothing else.

The capture, the layout and the block checks live in ``tests/_docs_sql.py``;
this module is the gate over the pages in ``PAGES``. Each named example runs
once per dialect in a subprocess, and each marked block is compared with what
its region sent. A block marked ``(postgres)`` runs under the
``postgres_only`` marker, against the database ``--db-backends`` selects.
"""

from __future__ import annotations

import asyncio
from pathlib import Path
from types import SimpleNamespace
from typing import Any

import pytest

from tests._docs_harness import DOCS_PAGES, Fence, fenced_blocks
from tests._docs_sql import (
    Capture,
    Region,
    Run,
    captured,
    check_block,
    check_same_on_postgres,
    layout,
    sql_marker,
    unlaid,
)

PAGES = [
    "guide/queries.md",
    "guide/aggregations.md",
    "guide/relationships.md",
    "guide/mutations.md",
    "guide/models-and-fields.md",
]
"""The pages whose every ```sql block is regenerated by this test."""


def _sql_blocks(page: str, text: str | None = None) -> list[Fence]:
    """Every ```sql block of ``page`` (or of ``text``, read as that page).

    A block that embeds an example's snippet (``--8<-- "docs/examples/..."``)
    is left out: it is a schema the example itself asserts equals what
    ``create_tables()`` ran, as the Models and fields guide's DDL blocks do.
    """
    path = DOCS_PAGES / page
    if text is None:
        text = path.read_text(encoding="utf-8")
    return [
        block
        for block in fenced_blocks(path, text, "sql")
        if not block.body.startswith("--8<--")
    ]


def _all_blocks() -> list[Fence]:
    return [block for page in PAGES for block in _sql_blocks(page)]


def _where(block: Fence) -> str:
    return f"{block.path.relative_to(DOCS_PAGES).as_posix()}:{block.line}"


# -- the layout -------------------------------------------------------------------


def test_layout_only_adds_line_breaks() -> None:
    sql = (
        'SELECT "t"."id" FROM "t" INNER JOIN "a" AS "x" ON "x"."id" = "t"."a_id" '
        'WHERE EXISTS (SELECT 1 FROM "s" WHERE "s"."t_id" = "t"."id") '
        'AND "t"."memo" = \'FROM x\' ORDER BY "t"."id" ASC LIMIT ? OFFSET ?'
    )
    laid = layout(sql)
    assert laid.splitlines() == [
        'SELECT "t"."id"',
        'FROM "t"',
        'INNER JOIN "a" AS "x" ON "x"."id" = "t"."a_id"',
        'WHERE EXISTS (SELECT 1 FROM "s" WHERE "s"."t_id" = "t"."id") '
        'AND "t"."memo" = \'FROM x\'',
        'ORDER BY "t"."id" ASC',
        "LIMIT ?",
        "OFFSET ?",
    ]
    assert unlaid(laid) == sql


def test_layout_puts_each_column_of_a_create_table_on_its_own_line() -> None:
    sql = (
        'CREATE TABLE IF NOT EXISTS "t" ( "id" integer NOT NULL, "a_id" integer, '
        'CONSTRAINT "fk_t_a_id_a" FOREIGN KEY ("a_id") REFERENCES "a" ("id") '
        "ON DELETE CASCADE )"
    )
    laid = layout(sql)
    assert laid.splitlines() == [
        'CREATE TABLE IF NOT EXISTS "t" (',
        '  "id" integer NOT NULL,',
        '  "a_id" integer,',
        '  CONSTRAINT "fk_t_a_id_a" FOREIGN KEY ("a_id") REFERENCES "a" ("id") '
        "ON DELETE CASCADE",
        ")",
    ]
    assert unlaid(laid) == sql


# -- the block check --------------------------------------------------------------


def _fake(regions: dict[str, Region]) -> Any:
    """A run of ``predicates.py`` whose regions did ``regions``."""
    return lambda example, dialect: Run(
        regions if example == "predicates.py" else {}, "", []
    )


SENT = _fake(
    {"first-query": Region(sent=['SELECT "id" FROM "transaction" WHERE "amount" <= ?'])}
)


def _page_with(body: str) -> Fence:
    [block] = _sql_blocks(
        "guide/queries.md", f"# Queries\n\nIt sends:\n\n```sql\n{body}```\n"
    )
    return block


def test_a_block_holding_what_its_region_sends_passes() -> None:
    check_block(
        _page_with(
            "-- predicates.py:first-query (sqlite)\n"
            'SELECT "id"\nFROM "transaction"\nWHERE "amount" <= ?;\n'
        ),
        SENT,
    )


@pytest.mark.parametrize(
    ("body", "message"),
    [
        (
            "-- predicates.py:first-query (sqlite)\n"
            'SELECT "id"\nFROM "transaction"\nWHERE "amount" < ?;\n',
            "guide/queries.md:5 (predicates.py:first-query, sqlite): the block differs",
        ),
        (
            'SELECT "id"\nFROM "transaction"\nWHERE "amount" <= ?;\n',
            "guide/queries.md:5: a ```sql block must open with a marker line",
        ),
        (
            "-- predicate.py:first-query (sqlite)\nSELECT 1;\n",
            "guide/queries.md:5 (predicate.py:first-query, sqlite): "
            "docs/examples/predicate.py does not exist",
        ),
        (
            "-- predicates.py:first-queries (sqlite)\nSELECT 1;\n",
            "guide/queries.md:5 (predicates.py:first-queries, sqlite): "
            "predicates.py has no snippet region 'first-queries'",
        ),
    ],
    ids=["edited", "unmarked", "unknown-example", "unknown-region"],
)
def test_a_block_that_is_not_what_its_region_sends_fails_naming_it(
    body: str, message: str
) -> None:
    with pytest.raises(AssertionError) as raised:
        check_block(_page_with(body), SENT)
    assert str(raised.value).startswith(message), str(raised.value)


def test_a_block_for_a_region_that_sends_nothing_fails_naming_it() -> None:
    block = _page_with("-- predicates.py:first-query (sqlite)\nSELECT 1;\n")
    with pytest.raises(AssertionError) as raised:
        check_block(block, _fake({}))
    assert str(raised.value).startswith(
        "guide/queries.md:5 (predicates.py:first-query, sqlite): "
        "the region 'first-query' of predicates.py sends nothing"
    )


def test_every_page_shows_sql() -> None:
    """Each of the four pages shows the SQL of its queries; none is left without."""
    for page in PAGES:
        assert _sql_blocks(page), f"{page} shows no SQL"


def test_a_block_differing_on_postgres_only_in_placeholders_stands_for_both() -> None:
    block = _page_with(
        "-- predicates.py:first-query (sqlite)\n"
        'SELECT "id"\nFROM "transaction"\nWHERE "amount" <= ?;\n'
    )
    numbered = 'SELECT "id" FROM "transaction" WHERE "amount" <= $1'
    check_same_on_postgres(block, _fake({"first-query": Region(sent=[numbered])}))

    cast = 'SELECT "id" FROM "transaction" WHERE "amount" <= CAST($1 AS numeric)'
    with pytest.raises(AssertionError) as raised:
        check_same_on_postgres(block, _fake({"first-query": Region(sent=[cast])}))
    assert str(raised.value).startswith(
        "guide/queries.md:5 (predicates.py:first-query, sqlite): the block stands "
        "for both databases"
    )


# -- the gate ---------------------------------------------------------------------


def _on(url: str | None) -> Any:
    return lambda example, dialect: captured(example, dialect, url)


def _dialect(block: Fence) -> str:
    """The dialect a block is marked for; an unmarked block counts as SQLite's,
    so it fails there naming itself."""
    marker = sql_marker(block)
    return marker["dialect"] if marker else "sqlite"


def _key(block: Fence) -> tuple[Path, str, str] | None:
    marker = sql_marker(block)
    return (block.path, marker["example"], marker["snippet"]) if marker else None


def _postgres_checked() -> list[Fence]:
    """Every block but a SQLite one whose region has a ``(postgres)`` twin."""
    twins = {_key(block) for block in _all_blocks() if _dialect(block) == "postgres"}
    return [
        block
        for block in _all_blocks()
        if not (
            _dialect(block) == "sqlite" and sql_marker(block) and _key(block) in twins
        )
    ]


@pytest.mark.parametrize(
    "block",
    [block for block in _all_blocks() if _dialect(block) == "sqlite"],
    ids=_where,
)
def test_a_sqlite_block_is_what_its_example_sends(block: Fence) -> None:
    check_block(block, _on(None))


@pytest.mark.postgres_only
@pytest.mark.parametrize("block", _postgres_checked(), ids=_where)
def test_a_block_is_what_its_example_sends_on_postgres(
    block: Fence, db_url: str
) -> None:
    """A ``(postgres)`` block is what its region sends on PostgreSQL; a SQLite
    block with no ``(postgres)`` twin is too, once placeholders are read alike."""
    if _dialect(block) == "postgres":
        check_block(block, _on(db_url))
        return
    check_same_on_postgres(block, _on(db_url))


# -- the capture, through what it reports -----------------------------------------


class _Rendered:
    def __init__(self, sql: str, dialect: str = "sqlite") -> None:
        self.sql, self.dialect = sql, dialect

    def __str__(self) -> str:
        return self.sql


SCRATCH = """\
async def main():
    # --8<-- [start:query]
    rows = await query()
    # --8<-- [end:query]
"""


def _capture_at(tmp_path: Path, line: int) -> Capture:
    """A capture of a scratch example whose line ``line`` is running now."""
    path = tmp_path / "scratch.py"
    path.write_text(SCRATCH, encoding="utf-8")
    capture = Capture(path, "sqlite")
    capture.on_line(SimpleNamespace(co_filename=str(path)), line)
    return capture


async def _returns(value: Any) -> Any:
    return value


async def _raises(error: Exception) -> Any:
    raise error


def test_a_terminal_whose_sql_raises_but_whose_call_succeeds_fails_the_capture(
    tmp_path: Path,
) -> None:
    capture = _capture_at(tmp_path, 3)
    with pytest.raises(AssertionError) as raised:
        asyncio.run(
            capture.run_terminal(
                lambda: _raises(ValueError("cannot render")), _returns([1, 2])
            )
        )
    assert str(raised.value).startswith(
        "scratch.py:3: .sql() raised ValueError('cannot render') but the call succeeded"
    ), str(raised.value)


def test_a_terminal_whose_sql_and_call_refuse_differently_fails_the_capture(
    tmp_path: Path,
) -> None:
    capture = _capture_at(tmp_path, 3)
    with pytest.raises(AssertionError, match=r"^scratch\.py:3: \.sql\(\) raised"):
        asyncio.run(
            capture.run_terminal(
                lambda: _raises(ValueError("no")), _raises(TypeError("no"))
            )
        )


def test_a_terminal_that_refuses_in_both_raises_its_error_and_records_nothing(
    tmp_path: Path,
) -> None:
    capture = _capture_at(tmp_path, 3)
    with pytest.raises(ValueError, match="refused"):
        asyncio.run(
            capture.run_terminal(
                lambda: _raises(ValueError("cannot")), _raises(ValueError("refused"))
            )
        )
    assert capture.by_region() == {"query": Region()}


def test_a_terminal_records_its_rendering_once_and_returns_its_result(
    tmp_path: Path,
) -> None:
    capture = _capture_at(tmp_path, 3)

    async def outer() -> Any:
        # A terminal another runs is rendered by the outer one only.
        inner = capture.run_terminal(
            lambda: _returns(_Rendered("SELECT 2")), _returns(2)
        )
        return await capture.run_terminal(
            lambda: _returns(_Rendered("SELECT 1")), inner
        )

    assert asyncio.run(outer()) == 2
    assert capture.by_region() == {"query": Region(sent=["SELECT 1"])}


EXAMPLE = """\
import asyncio

from ferro import Field, Model, connect, engines


class Note(Model):
    id: int | None = Field(default=None, primary_key=True)
    text: str


def show(notes):
    print([note.text for note in notes])


async def main():
    await connect("sqlite::memory:", auto_migrate=True)
    async with engines.session():
        # --8<-- [start:create]
        await Note.create(text="first")
        print("created")
        # --8<-- [end:create]
        # --8<-- [start:list]
        show(await Note.where(lambda note: note.id >= 1).all())
        # --8<-- [end:list]


asyncio.run(main())
"""


def test_a_run_reports_what_each_region_sends_and_prints(tmp_path: Path) -> None:
    script = tmp_path / "notes.py"
    script.write_text(EXAMPLE, encoding="utf-8")
    run = captured(script)
    assert run.regions["create"].printed == ["created"]
    assert [sql.split(" ")[0] for sql in run.regions["create"].sent] == ["INSERT"]
    # The helper prints outside any region; the line inside "list" that
    # called it owns the output.
    assert run.regions["list"].shown_output == "['first']\n"
    assert run.regions["list"].sent[0].startswith("SELECT ")
    assert run.stdout == "created\n['first']\n"
    assert run.schemas, "the run records the models' schema"
