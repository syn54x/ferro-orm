"""The SQL the query and mutation guides show is the SQL Ferro sends.

A page never carries SQL a person typed. Every ```sql block on the Queries,
Aggregations, Relationships and Mutations guides opens with a marker line
naming where its SQL comes from::

    -- predicates.py:first-query (sqlite)

that is, an example script in ``docs/examples/``, one of its snippet regions
(``# --8<-- [start:first-query]`` ... ``[end:first-query]``) and the dialect.
The block holds every statement that region sends, in order: a query
terminal's statement as its ``.sql()`` renders it, and any other statement
(``save()``, ``create()``, ``bulk_create()``, ``delete()`` on an instance, a
many-to-many ``add()``) as the statement log records it. Schema statements
(``migrate``), Postgres catalog probes (``catalog``), session settings and a
``transaction()`` block's own ``BEGIN`` / ``COMMIT`` are not shown.

Each statement is laid out with one clause per line (``_layout``), ends
with ``;`` and is set off from the next by a blank line. Joining a statement's lines with single spaces gives back the
rendered SQL byte for byte, so the layout adds line breaks and nothing else.

The test runs each named example once per dialect in a subprocess
(``python -m tests.test_docs_sql <example> <dialect> [url]``, the capture
below), records what every snippet region sent and compares each marked
block with that record. A block marked ``(postgres)`` runs under the
``postgres_only`` marker, against the database ``--db-backends`` selects.
"""

from __future__ import annotations

import io
import json
import logging
import os
import re
import subprocess
import sys
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
DOCS_PAGES = REPO_ROOT / "docs" / "pages"
DOCS_EXAMPLES = REPO_ROOT / "docs" / "examples"

PAGES = [
    "guide/queries.md",
    "guide/aggregations.md",
    "guide/relationships.md",
    "guide/mutations.md",
]
"""The pages whose every ```sql block is regenerated by this test."""

MARKER = re.compile(
    r"^-- (?P<example>[A-Za-z0-9_]+\.py):(?P<snippet>[A-Za-z0-9_-]+) "
    r"\((?P<dialect>sqlite|postgres)\)$"
)
"""The first line of a marked block: ``-- <example>.py:<snippet> (<dialect>)``."""

SNIPPET = re.compile(r"#\s*--8<--\s*\[(?P<edge>start|end):(?P<name>[A-Za-z0-9_-]+)\]")
"""A snippet region's start or end line in an example script."""

HIDDEN_OPERATIONS = frozenset({"migrate", "catalog", "settings", "transaction"})
"""Statement-log operations a block does not show: schema statements, the
Postgres catalog probe, session settings and a transaction block's own
statements."""

CLAUSES = (
    "FROM",
    "INNER JOIN",
    "LEFT JOIN",
    "WHERE",
    "GROUP BY",
    "HAVING",
    "ORDER BY",
    "LIMIT",
    "OFFSET",
    "SET",
    "VALUES",
    "ON CONFLICT",
    "RETURNING",
)
"""The keywords that start a new line of a laid-out statement, at the top
level of the statement only (never inside parentheses or quotes)."""


# -- the layout ------------------------------------------------------------------


def _layout(sql: str) -> str:
    """``sql`` laid out one clause per line.

    A line break replaces the single space before each top-level clause
    keyword (``CLAUSES``). A ``CREATE TABLE`` statement also puts each column
    and constraint of its parenthesised body on its own line, indented two
    spaces. Removing each line's indentation and joining the lines with
    single spaces gives back ``sql``.
    """
    table = sql.startswith("CREATE TABLE")
    breaks: dict[int, str] = {}
    depth = 0
    quote: str | None = None
    for index, char in enumerate(sql):
        if quote is not None:
            if char == quote:
                quote = None
            continue
        if char in "\"'":
            quote = char
        elif char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
        elif char != " ":
            continue
        elif depth == 0:
            rest = sql[index + 1 :]
            if any(
                rest.startswith(keyword)
                and (len(rest) == len(keyword) or rest[len(keyword)] in " (")
                for keyword in CLAUSES
            ):
                breaks[index] = "\n"
        elif table and depth == 1:
            # At depth 1 the body's own "(" or a "," between its items comes
            # before the space; its closing ")" comes after it.
            if sql[index - 1] in "(,":
                breaks[index] = "\n  "
            elif sql[index + 1 : index + 2] == ")":
                breaks[index] = "\n"
    return "".join(breaks.get(index, char) for index, char in enumerate(sql))


def _unlaid(laid: str) -> str:
    """The statement ``_layout`` laid out: its lines unindented and joined by spaces."""
    return " ".join(line.lstrip(" ") for line in laid.splitlines())


def _statements(sqls: list[str]) -> str:
    """The body a marked block holds for ``sqls``: each laid out and ending in
    ``;``, with a blank line between two statements."""
    return "\n".join(f"{_layout(sql)};\n" for sql in sqls)


# -- the pages' blocks -----------------------------------------------------------


@dataclass(frozen=True)
class SqlBlock:
    """One ```sql block on a page."""

    page: str
    """The page, relative to ``docs/pages``."""
    line: int
    """The line of the block's opening fence."""
    body: str
    """Everything between the fences, the fence's indentation removed."""

    @property
    def where(self) -> str:
        return f"{self.page}:{self.line}"

    @property
    def marker(self) -> re.Match[str] | None:
        return MARKER.match(self.body.partition("\n")[0])

    @property
    def shown(self) -> str:
        """The block's statements: its body after the marker line."""
        return self.body.partition("\n")[2]


FENCE = re.compile(
    r"^(?P<indent>[ \t]*)```(?P<info>[^\n]*)\n(?P<body>.*?)^(?P=indent)```",
    flags=re.DOTALL | re.MULTILINE,
)


def _sql_blocks(page: str, text: str | None = None) -> list[SqlBlock]:
    """Every ```sql block of ``page`` (or of ``text``, read as that page)."""
    if text is None:
        text = (DOCS_PAGES / page).read_text(encoding="utf-8")
    blocks = []
    for match in FENCE.finditer(text):
        if match["info"].strip().split(" ")[0] != "sql":
            continue
        body = "".join(
            line.removeprefix(match["indent"])
            for line in match["body"].splitlines(keepends=True)
        )
        blocks.append(SqlBlock(page, text.count("\n", 0, match.start()) + 1, body))
    return blocks


def _all_blocks() -> list[SqlBlock]:
    return [block for page in PAGES for block in _sql_blocks(page)]


def _snippet_ranges(source: str) -> dict[str, tuple[int, int]]:
    """Each snippet region of an example's ``source``, as its (start, end) lines."""
    starts: dict[str, int] = {}
    ranges: dict[str, tuple[int, int]] = {}
    for number, line in enumerate(source.splitlines(), start=1):
        match = SNIPPET.search(line)
        if match is None:
            continue
        if match["edge"] == "start":
            starts[match["name"]] = number
        elif match["name"] in starts:
            ranges[match["name"]] = (starts.pop(match["name"]), number)
    return ranges


def check_block(block: SqlBlock, sent: Callable[[str, str], dict[str, list[str]]]) -> None:
    """Assert ``block`` is marked and holds what its example's region sends.

    Args:
        block: The page's block.
        sent: Given an example script's name and a dialect, what each of its
            snippet regions sends, as ``{region: [sql, ...]}``.

    Raises:
        AssertionError: The block has no marker, names an example or region
            that does not exist, or differs from what the region sends. The
            message names the page, the line and the example.
    """
    marker = block.marker
    assert marker is not None, (
        f"{block.where}: a ```sql block must open with a marker line "
        f"'-- <example>.py:<snippet> (<dialect>)' naming where its SQL comes "
        f"from; this one opens with {block.body.partition(chr(10))[0]!r}"
    )
    example, snippet, dialect = marker["example"], marker["snippet"], marker["dialect"]
    named = f"{block.where} ({example}:{snippet}, {dialect})"
    path = DOCS_EXAMPLES / example
    assert path.is_file(), f"{named}: docs/examples/{example} does not exist"
    ranges = _snippet_ranges(path.read_text(encoding="utf-8"))
    assert snippet in ranges, f"{named}: {example} has no snippet region {snippet!r}"
    statements = sent(example, dialect).get(snippet, [])
    assert statements, f"{named}: the region {snippet!r} of {example} sends nothing"
    expected = _statements(statements)
    assert block.shown == expected, (
        f"{named}: the block differs from what {example}:{snippet} sends on "
        f"{dialect}. It sends:\n{expected}"
    )


# -- the tests --------------------------------------------------------------------


def test_layout_only_adds_line_breaks() -> None:
    sql = (
        'SELECT "t"."id" FROM "t" INNER JOIN "a" AS "x" ON "x"."id" = "t"."a_id" '
        'WHERE EXISTS (SELECT 1 FROM "s" WHERE "s"."t_id" = "t"."id") '
        'AND "t"."memo" = \'FROM x\' ORDER BY "t"."id" ASC LIMIT ? OFFSET ?'
    )
    laid = _layout(sql)
    assert laid.splitlines() == [
        'SELECT "t"."id"',
        'FROM "t"',
        'INNER JOIN "a" AS "x" ON "x"."id" = "t"."a_id"',
        'WHERE EXISTS (SELECT 1 FROM "s" WHERE "s"."t_id" = "t"."id") '
        "AND \"t\".\"memo\" = 'FROM x'",
        'ORDER BY "t"."id" ASC',
        "LIMIT ?",
        "OFFSET ?",
    ]
    assert _unlaid(laid) == sql


def test_layout_puts_each_column_of_a_create_table_on_its_own_line() -> None:
    sql = (
        'CREATE TABLE IF NOT EXISTS "t" ( "id" integer NOT NULL, "a_id" integer, '
        'CONSTRAINT "fk_t_a_id_a" FOREIGN KEY ("a_id") REFERENCES "a" ("id") '
        "ON DELETE CASCADE )"
    )
    laid = _layout(sql)
    assert laid.splitlines() == [
        'CREATE TABLE IF NOT EXISTS "t" (',
        '  "id" integer NOT NULL,',
        '  "a_id" integer,',
        '  CONSTRAINT "fk_t_a_id_a" FOREIGN KEY ("a_id") REFERENCES "a" ("id") '
        "ON DELETE CASCADE",
        ")",
    ]
    assert _unlaid(laid) == sql


SENT = {"predicates.py": {"first-query": ['SELECT "id" FROM "transaction" WHERE "amount" <= ?']}}


def _fake_sent(example: str, dialect: str) -> dict[str, list[str]]:
    return SENT.get(example, {})


def _page_with(body: str) -> SqlBlock:
    [block] = _sql_blocks(
        "guide/queries.md", f"# Queries\n\nIt sends:\n\n```sql\n{body}```\n"
    )
    return block


def test_a_block_holding_what_its_region_sends_passes() -> None:
    check_block(
        _page_with(
            "-- predicates.py:first-query (sqlite)\n"
            'SELECT "id"\nFROM "transaction"\nWHERE "amount" <= ?;\n'
        ),
        _fake_sent,
    )


@pytest.mark.parametrize(
    ("body", "message"),
    [
        (
            "-- predicates.py:first-query (sqlite)\n"
            'SELECT "id"\nFROM "transaction"\nWHERE "amount" < ?;\n',
            "guide/queries.md:5 (predicates.py:first-query, sqlite): the block differs",
        ),
        (
            'SELECT "id"\nFROM "transaction"\nWHERE "amount" <= ?;\n',
            "guide/queries.md:5: a ```sql block must open with a marker line",
        ),
        (
            "-- predicate.py:first-query (sqlite)\nSELECT 1;\n",
            "guide/queries.md:5 (predicate.py:first-query, sqlite): "
            "docs/examples/predicate.py does not exist",
        ),
        (
            "-- predicates.py:first-queries (sqlite)\nSELECT 1;\n",
            "guide/queries.md:5 (predicates.py:first-queries, sqlite): "
            "predicates.py has no snippet region 'first-queries'",
        ),
        (
            "-- predicates.py:typo (sqlite)\nSELECT 1;\n",
            "guide/queries.md:5 (predicates.py:typo, sqlite): "
            "the region 'typo' of predicates.py sends nothing",
        ),
    ],
    ids=["edited", "unmarked", "unknown-example", "unknown-region", "sends-nothing"],
)
def test_a_block_that_is_not_what_its_region_sends_fails_naming_it(
    body: str, message: str
) -> None:
    with pytest.raises(AssertionError) as raised:
        check_block(_page_with(body), _fake_sent)
    assert str(raised.value).startswith(message), str(raised.value)


def test_every_page_shows_sql() -> None:
    """Each of the four pages shows the SQL of its queries; none is left without."""
    for page in PAGES:
        assert _sql_blocks(page), f"{page} shows no SQL"


PLACEHOLDER = re.compile(r"\$\d+|\?")
"""A bind placeholder: SQLite's ``?`` or PostgreSQL's ``$1``."""


def check_same_on_postgres(
    block: SqlBlock, sent: Callable[[str, str], dict[str, list[str]]]
) -> None:
    """Assert a SQLite block stands for PostgreSQL too: the region sends the
    same statements there once each placeholder is read as ``?``.

    A region whose SQL differs in more than its placeholders shows a
    ``(postgres)`` block of its own, and this check does not apply to it.

    Raises:
        AssertionError: PostgreSQL's statements differ in more than their
            placeholders. The message names the page, the line and the example.
    """
    marker = block.marker
    assert marker is not None, f"{block.where}: a ```sql block has no marker line"
    example, snippet = marker["example"], marker["snippet"]
    statements = sent(example, "postgres").get(snippet, [])
    expected = PLACEHOLDER.sub("?", _statements(statements))
    assert PLACEHOLDER.sub("?", block.shown) == expected, (
        f"{block.where} ({example}:{snippet}, sqlite): the block stands for both "
        f"databases, but on postgres the region sends more than other "
        f"placeholders; show a (postgres) block beside it. It sends:\n"
        f"{_statements(statements)}"
    )


def test_a_block_differing_on_postgres_only_in_placeholders_stands_for_both() -> None:
    block = _page_with(
        "-- predicates.py:first-query (sqlite)\n"
        'SELECT "id"\nFROM "transaction"\nWHERE "amount" <= ?;\n'
    )
    numbered = {"first-query": ['SELECT "id" FROM "transaction" WHERE "amount" <= $1']}
    check_same_on_postgres(block, lambda example, dialect: numbered)

    cast = {
        "first-query": [
            'SELECT "id" FROM "transaction" WHERE "amount" <= CAST($1 AS numeric)'
        ]
    }
    with pytest.raises(AssertionError) as raised:
        check_same_on_postgres(block, lambda example, dialect: cast)
    assert str(raised.value).startswith(
        "guide/queries.md:5 (predicates.py:first-query, sqlite): the block stands "
        "for both databases"
    )


def _capture(example: str, dialect: str, url: str | None) -> dict[str, list[str]]:
    """What each snippet region of ``example`` sends on ``dialect``.

    The example runs with ``PYTHONHASHSEED=0``: ``save(only=...)`` and
    ``save(exclude=...)`` write their columns in the order of a Python set, so
    the order of their ``SET`` list follows string hashing.
    """
    command = [sys.executable, "-m", "tests.test_docs_sql", example, dialect]
    if url is not None:
        command.append(url)
    result = subprocess.run(
        command,
        capture_output=True,
        text=True,
        timeout=180,
        cwd=REPO_ROOT,
        env={**os.environ, "PYTHONHASHSEED": "0"},
    )
    assert result.returncode == 0, (
        f"capturing {example} on {dialect} failed\n"
        f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}"
    )
    return json.loads(result.stdout.strip().splitlines()[-1])


_captured: dict[tuple[str, str], dict[str, list[str]]] = {}
"""Each example's capture per dialect, made once per test session."""


def _sent_on(url: str | None) -> Callable[[str, str], dict[str, list[str]]]:
    def sent(example: str, dialect: str) -> dict[str, list[str]]:
        if (example, dialect) not in _captured:
            if not (DOCS_EXAMPLES / example).is_file():
                return {}
            _captured[example, dialect] = _capture(example, dialect, url)
        return _captured[example, dialect]

    return sent


def _dialect(block: SqlBlock) -> str:
    """The dialect a block is marked for; an unmarked block counts as SQLite's,
    so it fails there naming itself."""
    return block.marker["dialect"] if block.marker else "sqlite"


def _postgres_twins() -> set[tuple[str, str, str]]:
    """The (page, example, region) of every block marked ``(postgres)``."""
    return {
        (block.page, block.marker["example"], block.marker["snippet"])
        for block in _all_blocks()
        if block.marker and block.marker["dialect"] == "postgres"
    }


@pytest.mark.parametrize(
    "block",
    [block for block in _all_blocks() if _dialect(block) == "sqlite"],
    ids=lambda block: block.where,
)
def test_a_sqlite_block_is_what_its_example_sends(block: SqlBlock) -> None:
    check_block(block, _sent_on(None))


def _postgres_checked() -> list[SqlBlock]:
    """Every block but a SQLite one whose region has a ``(postgres)`` twin."""
    twins = _postgres_twins()
    return [
        block
        for block in _all_blocks()
        if not (
            block.marker
            and block.marker["dialect"] == "sqlite"
            and (block.page, block.marker["example"], block.marker["snippet"]) in twins
        )
    ]


@pytest.mark.postgres_only
@pytest.mark.parametrize("block", _postgres_checked(), ids=lambda block: block.where)
def test_a_block_is_what_its_example_sends_on_postgres(
    block: SqlBlock, db_url: str
) -> None:
    """A ``(postgres)`` block is what its region sends on PostgreSQL; a SQLite
    block with no ``(postgres)`` twin is too, once placeholders are read alike."""
    if _dialect(block) == "postgres":
        check_block(block, _sent_on(db_url))
        return
    check_same_on_postgres(block, _sent_on(db_url))


# -- the capture -------------------------------------------------------------------
#
# ``python -m tests.test_docs_sql <example> <dialect> [url]`` runs one example
# script as ``__main__`` and prints, as its last line, a JSON object mapping
# each snippet region to the statements sent while a line inside it ran.


class _Capture:
    """What one example run sends, attributed to the example line that sent it."""

    def __init__(self, path: Path, dialect: str) -> None:
        self.path = str(path)
        self.dialect = dialect
        self.examples = str(DOCS_EXAMPLES)
        self.where: tuple[str, int] | None = None
        """The docs example file and line running now."""
        self.depth = 0
        """How many terminals are running; their own statements are rendered."""
        self.sent: list[tuple[int, str]] = []
        self.printed: list[tuple[int, str]] = []
        self.pending = ""

    def on_line(self, code: Any, line: int) -> Any:
        if code.co_filename.startswith(self.examples):
            self.where = (code.co_filename, line)
            return None
        return sys.monitoring.DISABLE

    def record(self, sql: str) -> None:
        if self.where is not None and self.where[0] == self.path:
            self.sent.append((self.where[1], sql))

    def write(self, text: str) -> None:
        """Record each line the example prints, at the example line printing it."""
        self.pending += text
        *lines, self.pending = self.pending.split("\n")
        if self.where is not None and self.where[0] == self.path:
            self.printed.extend((self.where[1], line) for line in lines)

    def on_statement(self, record: logging.LogRecord) -> None:
        operation = getattr(record, "operation", None)
        if self.depth == 0 and operation not in HIDDEN_OPERATIONS:
            assert record.dialect == self.dialect, record.dialect  # type: ignore[attr-defined]
            self.record(record.sql)  # type: ignore[attr-defined]

    def by_region(self) -> dict[str, list[str]]:
        ranges = _snippet_ranges(Path(self.path).read_text(encoding="utf-8"))
        regions = {}
        for name, (start, end) in ranges.items():
            sent = [sql for line, sql in self.sent if start < line < end]
            printed = [text for line, text in self.printed if start < line < end]
            regions[name] = sent or printed
        return regions


def _run_capture(example: str, dialect: str, url: str | None) -> dict[str, list[str]]:
    import asyncio  # noqa: F401  (the example's own import, made early)
    import runpy

    import ferro
    from ferro.query.rendered import Terminal

    capture = _Capture(DOCS_EXAMPLES / example, dialect)

    class _Handler(logging.Handler):
        def emit(self, record: logging.LogRecord) -> None:
            capture.on_statement(record)

    logger = logging.getLogger("ferro.sql")
    logger.addHandler(_Handler())
    logger.setLevel(logging.DEBUG)

    call = Terminal.__call__

    def render_then_call(self: Terminal, *args: Any, **kwargs: Any) -> Any:
        # Called first, so a terminal that refuses its query before returning
        # an awaitable raises here, where the example expects it.
        awaitable = call(self, *args, **kwargs)

        async def run() -> Any:
            if capture.depth:  # a terminal another terminal runs: not rendered again
                return await awaitable
            capture.depth += 1
            try:
                try:
                    rendered = await self.sql(*args, **kwargs)
                except Exception:  # the call raises it too, and sends nothing
                    rendered = None
                if rendered is not None:
                    assert rendered.dialect == dialect, rendered.dialect
                    capture.record(str(rendered))
                return await awaitable
            finally:
                capture.depth -= 1

        return run()

    Terminal.__call__ = render_then_call  # type: ignore[method-assign]

    if url is not None:
        connect = ferro.connect

        async def connect_to(_url: str, *args: Any, **kwargs: Any) -> Any:
            return await connect(url, *args, **kwargs)

        ferro.connect = connect_to  # type: ignore[assignment]

    tool = 4
    sys.monitoring.use_tool_id(tool, "docs-sql")
    sys.monitoring.register_callback(tool, sys.monitoring.events.LINE, capture.on_line)
    sys.monitoring.set_events(tool, sys.monitoring.events.LINE)
    sys.path.insert(0, str(DOCS_EXAMPLES))
    stdout = sys.stdout

    class _Tee(io.TextIOBase):
        def write(self, text: str) -> int:
            capture.write(text)
            return stdout.write(text)

    sys.stdout = _Tee()
    try:
        runpy.run_path(str(DOCS_EXAMPLES / example), run_name="__main__")
    finally:
        sys.stdout = stdout
        sys.monitoring.set_events(tool, 0)
        sys.monitoring.free_tool_id(tool)
    return capture.by_region()


if __name__ == "__main__":
    example, dialect, *rest = sys.argv[1:]
    regions = _run_capture(example, dialect, rest[0] if rest else None)
    print(json.dumps(regions))
