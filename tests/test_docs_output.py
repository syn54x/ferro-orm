@pytest.mark.parametrize("block", page_fences("text"), ids=page_name)
def test_a_text_block_is_what_it_says_it_is(block: Fence) -> None:
    check_printed(block)


def _on_postgres(block: Fence) -> bool:
    """Whether a ``prints:`` block shows what something prints on PostgreSQL:
    an example region marked ``(postgres)``, or a ``backend=postgres`` fence."""
    if not block.note or block.note[0] != "prints":
        return False
    if block.note[1] == "above":
        fence = printing_fence(block)
        return fence is not None and on_postgres(fence)
    marker = PRINTS.match(block.note[1])
    return marker is not None and marker["dialect"] == "postgres"


def _postgres_blocks() -> list[Fence]:
    return [block for block in page_fences("text") if _on_postgres(block)]


@pytest.mark.postgres_only
@pytest.mark.parametrize("block", _postgres_blocks(), ids=page_name)
def test_a_postgres_text_block_is_what_its_example_prints_there(
    block: Fence, db_url: str, pg_role
) -> None:
    args = (db_url, pg_role("app"))
    check_printed(
        block,
        lambda example, dialect: captured(example, dialect, args=args),
        dialect="postgres",
        database_url=db_url,
    )


def _defined_exception_classes() -> set[type]:
    """Every exception class Ferro defines, internal ones included."""
    import ferro.migrations
    import ferro.migrations._chunk_loop  # noqa: F401 - defines BatchFailed

    found: set[type] = set()
    pending: list[type] = [BaseException]
    while pending:
        cls = pending.pop()
        pending.extend(cls.__subclasses__())
        if cls.__module__.split(".")[0] == "ferro":
            found.add(cls)
    return found


def _public_exception_names() -> set[str]:
    """The exception classes a reader can import by the name a page prints:
    those in ``ferro.__all__`` or ``ferro.migrations.__all__``, and the public
    classes ``ferro.exceptions`` defines."""
    import ferro
    import ferro.exceptions
    import ferro.migrations

    exported = {
        exported
        for module in (ferro, ferro.migrations)
        for name in module.__all__
        if isinstance(exported := vars(module).get(name), type)
    }
    return {
        cls.__name__
        for cls in _defined_exception_classes()
        if cls in exported
        or (cls.__module__ == "ferro.exceptions" and not cls.__name__.startswith("_"))
    }


def _ferro_exception_names() -> list[str]:
    """The name of every public exception class Ferro defines, longest first."""
    return sorted(_public_exception_names(), key=lambda name: (-len(name), name))


def _internal_exception_names() -> set[str]:
    """The exception classes Ferro defines that no public path exports."""
    return {cls.__name__ for cls in _defined_exception_classes()} - set(
        _public_exception_names()
    )


_EXCEPTION_LINE = re.compile(r"(?m)^\s*(?:[^\s:]+:\d+: )?(?:[\w.]*\.)?(\w+): ")
"""A line opening with an exception's name, as ``print`` of a raised error or
a traceback's last line shows it."""


def internal_exception_names_in(body: str) -> list[str]:
    """The internal Ferro exception classes a block prints by name; a reader
    who writes ``except`` with one of them gets a ``NameError``."""
    internal = _internal_exception_names()
    return [name for name in _EXCEPTION_LINE.findall(body) if name in internal]


FERRO_OUTPUT = re.compile(
    r"(?m)^\s*(?:[^\s:]+:\d+: )?"  # a warning's or a traceback's `path:N: `
    r"(?:ferro\."
    r"|ferro (?:auto-)?migrate(?: [a-z]+)?: "
    rf"|(?:[\w.]*\.)?(?:{'|'.join(_ferro_exception_names())}):"
    r"|[\w.]*(?:Error|Refused|Warning|Exception):"
    r"|Traceback \(most recent call last\)"
    r'|File "[^"]+", line \d+, in '
    r"|\d+ validation errors? for "
    r"|connect\("
    r"|No database route "
    r"|Cannot add NOT NULL column "
    r"|\S+ \u00b7 \S+$"  # the `<database> · <target>` line every verb but init opens with
    r"|Wrote (?:ferro\.toml|\[tool\.ferro\]) "
    r"|\S+\.toml: "
    r"|\S+ holds two ferro configs"
    r"|squash --from \S+: "
    r"|changing the primary key of \S+ is not generated"
    r")"
)
"""A line that reads like something Ferro prints, raises or warns: an
exception or warning line (with its ``path:N:`` prefix, if any), a
``ferro migrate`` output or refusal, or one of Ferro's own messages."""


VARIES = {
    "guide/connections.md:333": "the statement log's lines end with how long "
    "each statement took, which differs on every run",
}
"""The ``shows:`` blocks holding Ferro's output that no run reproduces byte
for byte, by page and line, and why."""


_PRINTS_A_MESSAGE = re.compile(
    r"print\((?:f\"\{type\((\w+)\)\.__name__\}: \{\1\}\"|\w+\.message)\)"
)
"""A ``print`` of what was raised (``f"{type(error).__name__}: {error}"``) or
warned (``warning.message``), the forms the conventions give."""


def _shows_a_message(block: Fence) -> bool:
    """Whether a block shows Ferro's own words: ``ferro migrate``'s output or
    a refusal, or a ``prints:`` block whose source prints what Ferro raised or
    warned."""
    kind, value = block.note or ("", "")
    if kind in ("output", "refusal"):
        return True
    if kind != "prints":
        return False
    if value == "above":
        fence = printing_fence(block)
        source = fence.source if fence is not None else ""
    else:
        marker = PRINTS.match(value)
        assert marker is not None, page_name(block)
        script = REPO_ROOT / "docs" / "examples" / marker["example"]
        regions = snippet_regions(script.read_text(encoding="utf-8"))
        source = regions[marker["snippet"]].body
    return _PRINTS_A_MESSAGE.search(source) is not None


def _ferro_output_blocks() -> list[Fence]:
    """Every block the pages show as Ferro's own words."""
    return [block for block in page_fences("text") if _shows_a_message(block)]


@pytest.mark.parametrize(
    "line",
    [
        "No database route for this operation. Open a session",
        "Cannot add NOT NULL column 'author.bio' to an existing table",
        "ferro.exceptions.ModelDoesNotExist: Author with pk 7 does not exist",
        '  File "app.py", line 3, in <module>',
        "ferro.migrations.BatchFailed: batch 3 failed",
        "app.py:12: UserWarning: Check constraint 'ck_author_kind' is declared",
        "Traceback (most recent call last):",
        "ferro migrate: this database has applied 0002_author_slug",
        "ferro migrate squash: nothing to squash",
    ],
)
def test_the_recogniser_knows_each_kind_of_ferro_output(line: str) -> None:
    assert FERRO_OUTPUT.search(line), line


@pytest.mark.parametrize("block", _ferro_output_blocks(), ids=page_name)
def test_the_recogniser_matches_every_block_of_ferro_output(block: Fence) -> None:
    """The ``shows:`` guard is only as good as this pattern: it must match every
    block the pages already show as Ferro's output."""
    assert FERRO_OUTPUT.search(block.body), (
        f"{page_name(block)}: FERRO_OUTPUT does not recognise this block of "
        f"Ferro's output, so a <!-- shows: --> block holding it would pass:\n"
        f"{block.body}"
    )


@pytest.mark.parametrize("block", page_fences("text"), ids=page_name)
def test_a_printed_exception_name_is_one_a_reader_can_import(block: Fence) -> None:
    internal = internal_exception_names_in(block.body)
    assert not internal, (
        f"{page_name(block)}: the block prints {internal}, which neither "
        "ferro nor ferro.migrations exports; export and document the class, "
        "or print its nearest public base"
    )


def test_a_block_naming_an_internal_exception_class_fails() -> None:
    assert "StepRefused" in _internal_exception_names()
    assert internal_exception_names_in(
        "Step refused:\nStepRefused: the step needs a reason\n"
    ) == ["StepRefused"]
    assert internal_exception_names_in(
        "ferro.migrations.steps.StepRefused: the step needs a reason\n"
    ) == ["StepRefused"]
    assert internal_exception_names_in("MigrationRefused: refused\n") == []


def test_the_recogniser_names_only_public_exception_classes() -> None:
    names = set(_ferro_exception_names())
    assert "MigrationRefused" in names
    assert not names & _internal_exception_names()


def test_each_varies_entry_names_a_shows_block() -> None:
    shows = {
        page_name(block)
        for block in page_fences("text")
        if block.note and block.note[0] == "shows"
    }
    stale = sorted(set(VARIES) - shows)
    assert not stale, f"VARIES names no shows: block at {stale}; update the line"


@pytest.mark.parametrize(
    "block",
    [block for block in page_fences("text") if block.note and block.note[0] == "shows"],
    ids=page_name,
)
def test_a_shows_block_holds_nothing_ferro_prints(block: Fence) -> None:
    if page_name(block) in VARIES:
        return
    line = FERRO_OUTPUT.search(block.body)
    assert line is None, (
        f"{page_name(block)}: a <!-- shows: --> block quotes what Ferro prints "
        f"({line.group(0)!r}...); make it a <!-- prints: --> block backed by an "
        "example region that triggers it"
    )


def _fake(example: str, dialect: str) -> Run:
    regions = {"first-query": Region(printed=["Rent -1450", "Groceries -82.40"])}
    return Run(regions if example == "predicates.py" else {}, "", [])


def _block(note: str, body: str) -> Fence:
    [block] = fenced_blocks(
        Path("docs/pages/guide/queries.md"),
        f"# Queries\n\nIt prints:\n\n{note}\n```text\n{body}```\n",
        "text",
    )
    return block


def test_a_block_holding_what_its_region_prints_passes() -> None:
    check_printed(
        _block(
            "<!-- prints: predicates.py:first-query -->",
            "Rent -1450\nGroceries -82.40\n",
        ),
        _fake,
    )


def test_a_block_that_says_what_it_shows_is_not_compared() -> None:
    check_printed(_block("<!-- shows: a traceback -->", "Traceback\n"), _fake)


def _page_below(tmp_path: Path, fence: str, body: str) -> Fence:
    page = tmp_path / "page.md"
    page.write_text(
        f"# Page\n\n{fence}\n\nIt prints:\n\n<!-- prints: above -->\n```text\n"
        f"{body}```\n",
        encoding="utf-8",
    )
    [block] = fenced_blocks(page, page.read_text(encoding="utf-8"), "text")
    return block


RUN_FENCE = (
    "```python {test=run prelude=reference}\n"
    "print((await Author.where(lambda author: author.id == 1).first()).name)\n```"
)


def test_a_block_under_a_run_fence_holds_what_the_fence_prints(
    tmp_path: Path,
) -> None:
    check_printed(_page_below(tmp_path, RUN_FENCE, "Ada Lovelace\n"))
    with pytest.raises(AssertionError) as raised:
        check_printed(_page_below(tmp_path, RUN_FENCE, "Grace Hopper\n"))
    assert "the block differs from what the fence at line 3 prints" in str(raised.value)


def test_a_block_under_a_fence_that_does_not_run_is_refused(tmp_path: Path) -> None:
    fence = '```python {test=compile reason="needs Postgres"}\nprint(1)\n```'
    with pytest.raises(AssertionError, match=r"needs the fence above \(line 3\)"):
        check_printed(_page_below(tmp_path, fence, "1\n"))


