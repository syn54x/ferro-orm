"""The output a page shows is what its example prints.

Every ```text block on a docs page sits under a note saying where its text
comes from (``tests._docs_sql.TEXT_NOTES``):

- ``<!-- prints: <example>.py:<snippet> -->``: what that snippet region of
  ``docs/examples/<example>.py`` prints. This test runs the script once on
  SQLite and compares the block with the region's printed lines byte for byte.
- ``<!-- prints: <example>.py:<snippet> (postgres) -->``: what the region
  prints on PostgreSQL, where the script runs as
  ``<example>.py <database-url> <role>`` (a fresh schema and a role name the
  test owns), under the ``postgres_only`` marker.
- ``<!-- prints: above -->``: what the nearest Python fence above it prints,
  a fence marked ``{test=run prelude=<name>}``, run the way
  ``tests/test_docs_examples.py`` runs it.
- ``<!-- output: <id> -->`` and ``<!-- refusal: <id> -->``: what
  ``ferro migrate`` prints, regenerated by ``tests/test_docs_migrations.py``.
- ``<!-- shows: <what it is> -->``: text Ferro does not print (a sketch, a
  file tree, another tool's shell session, a prompt to paste), skipped on
  purpose and saying so. Ferro's own errors and warnings are ``prints:`` blocks,
  and a ``shows:`` block that reads like one is refused.

An unmarked block is refused, so typed output cannot slip onto a page.
"""

from __future__ import annotations

from pathlib import Path

import re

import pytest

from tests._docs_harness import Fence, fenced_blocks, page_fences
from tests._docs_sql import (
    PRINTS,
    Region,
    Run,
    printing_fence,
    captured,
    on_postgres,
    check_printed,
    page_name,
)


@pytest.mark.parametrize("block", page_fences("text"), ids=page_name)
def test_a_text_block_is_what_it_says_it_is(block: Fence) -> None:
    check_printed(block)


def _on_postgres(block: Fence) -> bool:
    """Whether a ``prints:`` block shows what something prints on PostgreSQL:
    an example region marked ``(postgres)``, or a ``backend=postgres`` fence."""
    if not block.note or block.note[0] != "prints":
        return False
    if block.note[1] == "above":
        fence = printing_fence(block)
        return fence is not None and on_postgres(fence)
    marker = PRINTS.match(block.note[1])
    return marker is not None and marker["dialect"] == "postgres"


def _postgres_blocks() -> list[Fence]:
    return [block for block in page_fences("text") if _on_postgres(block)]


@pytest.mark.postgres_only
@pytest.mark.parametrize("block", _postgres_blocks(), ids=page_name)
def test_a_postgres_text_block_is_what_its_example_prints_there(
    block: Fence, db_url: str, pg_role
) -> None:
    args = (db_url, pg_role("app"))
    check_printed(
        block,
        lambda example, dialect: captured(example, dialect, args=args),
        dialect="postgres",
        database_url=db_url,
    )


FERRO_OUTPUT = re.compile(
    r"(?m)^(?:ferro\.|ferro auto-migrate:|[\w.]*(?:Error|Refused|Warning):"
    r"|\d+ validation errors? for |connect\()"
)
"""A line that reads like something Ferro prints, raises or warns."""


VARIES = {
    "guide/connections.md": "the statement log's lines end with how long each "
    "statement took, which differs on every run",
}
"""Pages whose ``shows:`` block holds Ferro's output that no run reproduces
byte for byte, and why."""


@pytest.mark.parametrize(
    "block",
    [block for block in page_fences("text") if block.note and block.note[0] == "shows"],
    ids=page_name,
)
def test_a_shows_block_holds_nothing_ferro_prints(block: Fence) -> None:
    if page_name(block).rsplit(":", 1)[0] in VARIES:
        return
    line = FERRO_OUTPUT.search(block.body)
    assert line is None, (
        f"{page_name(block)}: a <!-- shows: --> block quotes what Ferro prints "
        f"({line.group(0)!r}...); make it a <!-- prints: --> block backed by an "
        "example region that triggers it"
    )


def _fake(example: str, dialect: str) -> Run:
    regions = {"first-query": Region(printed=["Rent -1450", "Groceries -82.40"])}
    return Run(regions if example == "predicates.py" else {}, "", [])


def _block(note: str, body: str) -> Fence:
    [block] = fenced_blocks(
        Path("docs/pages/guide/queries.md"),
        f"# Queries\n\nIt prints:\n\n{note}\n```text\n{body}```\n",
        "text",
    )
    return block


def test_a_block_holding_what_its_region_prints_passes() -> None:
    check_printed(
        _block(
            "<!-- prints: predicates.py:first-query -->",
            "Rent -1450\nGroceries -82.40\n",
        ),
        _fake,
    )


def test_a_block_that_says_what_it_shows_is_not_compared() -> None:
    check_printed(_block("<!-- shows: a traceback -->", "Traceback\n"), _fake)


def _page_below(tmp_path: Path, fence: str, body: str) -> Fence:
    page = tmp_path / "page.md"
    page.write_text(
        f"# Page\n\n{fence}\n\nIt prints:\n\n<!-- prints: above -->\n```text\n"
        f"{body}```\n",
        encoding="utf-8",
    )
    [block] = fenced_blocks(page, page.read_text(encoding="utf-8"), "text")
    return block


RUN_FENCE = (
    "```python {test=run prelude=reference}\n"
    "print((await Author.where(lambda author: author.id == 1).first()).name)\n```"
)


def test_a_block_under_a_run_fence_holds_what_the_fence_prints(
    tmp_path: Path,
) -> None:
    check_printed(_page_below(tmp_path, RUN_FENCE, "Ada Lovelace\n"))
    with pytest.raises(AssertionError) as raised:
        check_printed(_page_below(tmp_path, RUN_FENCE, "Grace Hopper\n"))
    assert "the block differs from what the fence at line 3 prints" in str(raised.value)


def test_a_block_under_a_fence_that_does_not_run_is_refused(tmp_path: Path) -> None:
    fence = '```python {test=compile reason="needs Postgres"}\nprint(1)\n```'
    with pytest.raises(AssertionError, match=r"needs the fence above \(line 3\)"):
        check_printed(_page_below(tmp_path, fence, "1\n"))


@pytest.mark.parametrize(
    ("note", "body", "message"),
    [
        (
            "<!-- prints: predicates.py:first-query -->",
            "Rent -1450\n",
            "docs/pages/guide/queries.md:6 (predicates.py:first-query): the block "
            "differs from what predicates.py:first-query prints",
        ),
        (
            "",
            "Rent -1450\nGroceries -82.40\n",
            "docs/pages/guide/queries.md:6: a ```text block must sit under a note",
        ),
        (
            "<!-- printed: predicates.py:first-query -->",
            "Rent -1450\n",
            "docs/pages/guide/queries.md:6: unknown note 'printed'",
        ),
        (
            "<!-- prints: predicates.py -->",
            "Rent -1450\n",
            "docs/pages/guide/queries.md:6: <!-- prints: predicates.py --> must name",
        ),
        (
            "<!-- prints: predicates.py:no-such-region -->",
            "Rent -1450\n",
            "docs/pages/guide/queries.md:6 (predicates.py:no-such-region): "
            "predicates.py has no snippet region 'no-such-region'",
        ),
    ],
    ids=["edited", "unmarked", "unknown-note", "no-region", "unknown-region"],
)
def test_a_block_that_is_not_what_it_says_fails_naming_it(
    note: str, body: str, message: str
) -> None:
    with pytest.raises(AssertionError) as raised:
        check_printed(_block(note, body), _fake)
    assert str(raised.value).startswith(message), str(raised.value)


PG_FENCE = (
    "```python {test=run prelude=reference backend=postgres}\n"
    "from ferro import fetch_one\n\n"
    'row = await fetch_one("SELECT version() AS v")\nprint(row["v"].split()[0])\n```'
)


def test_a_block_under_a_postgres_fence_is_compared_only_on_postgres(
    tmp_path: Path,
) -> None:
    """On SQLite the fence above is only found and its marker checked; the
    PostgreSQL job runs it and compares."""
    block = _page_below(tmp_path, PG_FENCE, "anything\n")
    check_printed(block)
    assert printing_fence(block) is not None


@pytest.mark.postgres_only
@pytest.mark.parametrize("shown", ["PostgreSQL\n", "SQLite\n"], ids=["same", "edited"])
def test_a_block_under_a_postgres_fence_holds_what_it_prints_there(
    tmp_path: Path, db_url: str, shown: str
) -> None:
    block = _page_below(tmp_path, PG_FENCE, shown)
    if shown == "PostgreSQL\n":
        check_printed(block, dialect="postgres", database_url=db_url)
        return
    with pytest.raises(AssertionError, match="differs from what the fence at line 3"):
        check_printed(block, dialect="postgres", database_url=db_url)
